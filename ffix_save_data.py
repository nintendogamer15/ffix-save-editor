LEGACY_BYTE_TO_CHAR: dict[int, str] = {v: k for k, v in LEGACY_CHAR_TO_BYTE.items()}
LEGACY_NAME_TERMINATOR = 0xFF


def encode_legacy_text(text: str, length: int) -> bytes:
    out = bytearray()
    for ch in text[:length]:
        out.append(LEGACY_CHAR_TO_BYTE.get(ch, LEGACY_CHAR_TO_BYTE['?']))
    while len(out) < length:
        out.append(LEGACY_NAME_TERMINATOR)
    return bytes(out[:length])


def decode_legacy_text(data: bytes) -> str:
    out = []
    for b in data:
        if b == LEGACY_NAME_TERMINATOR:
            break
        ch = LEGACY_BYTE_TO_CHAR.get(b)
        if ch is not None:
            out.append(ch)
    return ''.join(out)
