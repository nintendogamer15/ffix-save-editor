def _build_lookup(names: list[str]) -> dict[str, int]:
    lookup: dict[str, int] = {}
    for idx, name in enumerate(names):
        key = name.strip().lower()
        if key and key not in lookup:
            lookup[key] = idx
    return lookup


ITEM_NAME_TO_ID = _build_lookup(ITEM_NAMES)
SUPPORT_ABILITY_NAME_TO_ID = _build_lookup(SUPPORT_ABILITY_NAMES)
CARD_TYPE_NAME_TO_ID = _build_lookup(CARD_TYPE_NAMES)

EMPTY_ITEM_ID = ITEM_NAMES.index("Nothing")
NO_CARD_TYPE = 0xFF


def item_name(item_id: int) -> str:
    if 0 <= item_id < len(ITEM_NAMES):
        return ITEM_NAMES[item_id]
    return f"0x{item_id:02X}"


def support_ability_name(bit_index: int) -> str:
    if 0 <= bit_index < len(SUPPORT_ABILITY_NAMES):
        return SUPPORT_ABILITY_NAMES[bit_index]
    return f"bit{bit_index}"


def card_type_name(type_id: int) -> str:
    if type_id == NO_CARD_TYPE or not (0 <= type_id < len(CARD_TYPE_NAMES)):
        return "(none)"
    return CARD_TYPE_NAMES[type_id]


def resolve_item_id(token: str) -> int:
    token = token.strip()
    if not token:
        raise ValueError("empty item name/ID")
    try:
        base = 16 if token.lower().startswith("0x") else 10
        value = int(token, base)
    except ValueError:
        value = None
    if value is not None:
        if not (0 <= value <= 0xFF):
            raise ValueError(f"item ID out of range 0-255: {value}")
        return value
    key = token.lower()
    if key in ITEM_NAME_TO_ID:
        return ITEM_NAME_TO_ID[key]
    matches = [n for n in ITEM_NAMES if key in n.lower()]
    if len(matches) == 1:
        return ITEM_NAME_TO_ID[matches[0].lower()]
    if len(matches) > 1:
        raise ValueError(f"ambiguous item name {token!r}: matches {', '.join(matches[:8])}")
    raise ValueError(f"unknown item name/ID: {token!r}")


